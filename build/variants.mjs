//   시안의 청소 서비스 페이지 문장을 근거로 작성했다 → 발주자 확인 필요 항목으로 보고서에 올린다.

const set = ($, root, sel, html) => { const e = root.find(sel); if (!e.length) throw new Error('selector ' + sel); e.first().html(html); };
const setAll = ($, root, sel, list) => { root.find(sel).each((i, e) => { if (list[i] != null) $(e).html(list[i]); }); };

function common($, root, v) {
  set($, root, '.hero-split .q', v.q);
  set($, root, '.hero-split h1', v.h1);
  set($, root, '.hero-split .desc', v.desc);
  setAll($, root, '.hero-split .miniticks span', v.ticks);
  set($, root, '.painhead .quote', v.quote);
  root.find('.pains .pain').each((i, e) => {
    const p = v.pains[i]; if (!p) return;
    $(e).find('.ic').text(p[0]); $(e).find('b').first().text(p[1]); $(e).find('p').first().text(p[2]);
  });
  const d1 = root.find('.diff').eq(0);
  d1.find('.ph .chip').text(v.d1.chip); d1.find('.ph > span').not('.chip,.pt').text(v.d1.ph);
  d1.find('h3').html(v.d1.h3); d1.find('.txt > p').html(v.d1.p);
  d1.find('.checks li').each((i, e) => $(e).text(v.d1.checks[i]));
  const d3 = root.find('.diff').eq(2);
  d3.find('.txt > p').html(v.d3.p);
  d3.find('.estimate .row div').each((i, e) => { const b = $(e).find('b'); $(e).empty().append(b).append(v.d3.rows[i]); });
  const cta = root.find('section.cta').last();
  cta.find('h2').html(v.cta.h2);
  if (v.cta.p) cta.find('.p').html(v.cta.p);
  cta.find('.ctabox .t').text(v.cta.t);
  cta.find('.ctabox li').each((i, e) => $(e).text(v.cta.items[i]));
  if (v.cta.btn) cta.find('.btns a').first().text(v.cta.btn);
}


